export interface ProfitRuleConfig {
  mode: 'percentage' | 'flat';
  value: number; // e.g. 10 for 10% or 20 for +₹20
}

export const DEFAULT_PROFIT_RULE: ProfitRuleConfig = {
  mode: 'percentage',
  value: 10, // 10% markup over wholesale mart purchase price
};

/**
 * Calculates customer selling price strictly constrained at or below printed MRP
 */
export function calculateMartSellingPrice(
  martBasePrice: number,
  mrp: number,
  rule: ProfitRuleConfig = DEFAULT_PROFIT_RULE
): { sellingPrice: number; discountPercent: number; profitAmount: number } {
  let calculated: number;
  if (rule.mode === 'percentage') {
    calculated = Math.round(martBasePrice * (1 + rule.value / 100));
  } else {
    calculated = Math.round(martBasePrice + rule.value);
  }

  // Strictly enforce selling price <= printed MRP
  const sellingPrice = Math.max(martBasePrice, Math.min(mrp, calculated));
  const profitAmount = Math.max(0, sellingPrice - martBasePrice);
  const discountPercent = mrp > sellingPrice && mrp > 0 ? Math.round(((mrp - sellingPrice) / mrp) * 100) : 0;

  return { sellingPrice, discountPercent, profitAmount };
}

/**
 * Normalized duplicate detection between mart item and store products
 */
export function isMartItemInStore(martItem: MartItem, storeProducts: { id: string; name: string }[]): boolean {
  if (storeProducts.some((p) => p.id === martItem.id)) return true;

  const cleanMartName = martItem.productName.toLowerCase().replace(/[^a-z0-9]/g, '');
  return storeProducts.some((p) => {
    const cleanProdName = p.name.toLowerCase().replace(/[^a-z0-9]/g, '');
    return cleanProdName === cleanMartName || (cleanMartName.length > 8 && cleanProdName.includes(cleanMartName));
  });
}
